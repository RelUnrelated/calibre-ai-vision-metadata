def _next_language_code(value):
    normalized = str(value).strip()
    if not normalized:
        return ''
    folded = normalized.casefold()
    for code, name in _LANGUAGE_NAMES.items():
        if folded == name.casefold():
            return 'zho' if code == 'chi' else ('jpn' if code == 'ja' else ('eng' if code == 'en' else code))
    return normalized

def _canonical_authors(value):
    parts = [part.strip() for part in re.split(r'\s*(?:&|,|，|、)\s*', str(value or '')) if part.strip()]
    return ' & '.join(parts)
def _(text: str) -> str:
    return _ZH_UI.get(text, _CALIBRE_TRANSLATE(text))

