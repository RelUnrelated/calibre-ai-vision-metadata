        for opt in index_options:
            val = opt[0]
            try:
                float(val)
                if '.' in val:
                    if len(val.split('.')[-1]) <= 2:
                        filtered_index_options.append(opt)
                else:
                    filtered_index_options.append(opt)
            except ValueError:
                pass

